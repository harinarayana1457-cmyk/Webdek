import React, { useState } from 'react';
import { X, Copy, Check, Download, FileText, Code2 } from 'lucide-react';
import { animate, spring } from 'animejs';
import { useAnimeScope } from '../hooks/useAnimeScope';
import { ProjectAnalysisResult } from '../../engine/types';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  data: ProjectAnalysisResult;
}

export const ExportModal: React.FC<ExportModalProps> = ({ isOpen, onClose, data }) => {
  const [format, setFormat] = useState<'markdown' | 'json'>('markdown');
  const [copied, setCopied] = useState(false);

  const { root } = useAnimeScope(() => {
    if (!isOpen) return;

    animate('.export-modal-card', {
      scale: [0.94, 1],
      opacity: [0, 1],
      translateY: [-12, 0],
      duration: 350,
      ease: spring({ bounce: 0.35 })
    });
  }, [isOpen]);

  if (!isOpen) return null;

  const generateMarkdown = (): string => {
    return `# Software Architecture & Stack Analysis: ${data.projectName}
Generated by **ProjectLens** on ${new Date(data.timestamp).toLocaleString()}

## 1. Architectural Blueprint
- **Architecture Pattern:** ${data.architecture.pattern} (${data.architecture.confidence}% Confidence)
- **Primary Framework:** ${data.primaryFramework}
- **Runtime:** ${data.primaryRuntime}
- **Styling Engine:** ${data.stylingEngine}
- **State Management:** ${data.stateLayer}
- **AI Stack:** ${data.aiLayer}
- **AI Readiness Score:** ${data.aiConfig.readinessScore}/100

### Architecture Summary
${data.architecture.summary}

### Data Flow Journey
\`${data.architecture.dataFlowSummary}\`

## 2. Tech Stack & Package Specifications (${data.dependencies.length} Packages)
| Package | Category | Level | Role & Purpose | Architectural Significance |
|---|---|---|---|---|
${data.dependencies
  .map(
    (d) =>
      `| **${d.name}** | \`${d.category}\` | ${d.level.toUpperCase()} | ${d.purpose.replace(/\|/g, '-')} | ${d.significance.replace(/\|/g, '-')} |`
  )
  .join('\n')}

## 3. AI Assistant & Developer Workspace Setup
- Cursor Rules (.cursorrules): ${data.aiConfig.hasCursorRules ? 'Configured' : 'Not detected'}
- Claude / Agent Directives (CLAUDE.md): ${data.aiConfig.hasClaudeInstructions ? 'Configured' : 'Not detected'}
- Model Context Protocol (MCP) Servers: ${data.aiConfig.mcpServers.length} configured
- Environment Variables Detected: ${data.aiConfig.environmentKeys.join(', ') || 'None'}

### Developer Recommendations
${data.aiConfig.recommendations.map((r) => `- ${r}`).join('\n') || '- Codebase follows clean architectural conventions.'}

---
*Generated by ProjectLens - Comprehensive Codebase Intelligence Engine*
`;
  };

  const content = format === 'markdown' ? generateMarkdown() : JSON.stringify(data, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `${data.projectName.toLowerCase().replace(/\s+/g, '-')}-architecture.${
      format === 'markdown' ? 'md' : 'json'
    }`;
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div ref={root} className="fixed inset-0 bg-black/75 backdrop-blur-md z-50 flex items-center justify-center p-4 animate-in fade-in duration-200">
      <div className="export-modal-card bg-[#0c1427] border border-slate-750 rounded-2xl w-full max-w-3xl shadow-2xl flex flex-col max-h-[85vh] overflow-hidden relative">
        {/* Top Accent Stripe */}
        <div className="h-1 w-full bg-gradient-to-r from-indigo-500 via-sky-400 to-indigo-600" />

        {/* Header */}
        <div className="flex items-center justify-between p-5 px-6 border-b border-slate-800 bg-slate-900/90">
          <div className="flex items-center gap-3.5">
            <div className="w-10 h-10 rounded-xl bg-indigo-500/15 border border-indigo-500/30 text-indigo-400 flex items-center justify-center shadow-sm">
              <Download className="w-5 h-5 text-indigo-400" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="font-bold text-base text-white tracking-tight">
                  Export Architecture Report
                </h3>
                <span className="text-[10px] uppercase font-mono px-2 py-0.5 rounded-full bg-indigo-500/15 text-indigo-300 border border-indigo-500/25 font-bold">
                  PROJECT REPORT
                </span>
              </div>
              <p className="text-[11px] text-slate-400">Download architecture specifications for documentation, PRs, and team handoffs</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-white/10 transition"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Format Selector Bar */}
        <div className="flex items-center justify-between px-6 py-3 bg-slate-900/60 border-b border-slate-800 text-xs">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setFormat('markdown')}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg transition font-mono text-xs font-semibold ${
                format === 'markdown'
                  ? 'bg-indigo-600 text-white shadow-md shadow-indigo-500/25'
                  : 'text-slate-300 hover:text-white bg-slate-800/80 border border-slate-700'
              }`}
            >
              <FileText className="w-3.5 h-3.5 text-indigo-300" />
              Markdown (.md)
            </button>
            <button
              onClick={() => setFormat('json')}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg transition font-mono text-xs font-semibold ${
                format === 'json'
                  ? 'bg-indigo-600 text-white shadow-md shadow-indigo-500/25'
                  : 'text-slate-300 hover:text-white bg-slate-800/80 border border-slate-700'
              }`}
            >
              <Code2 className="w-3.5 h-3.5 text-indigo-300" />
              JSON (.json)
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 text-xs bg-slate-800 hover:bg-slate-700 text-white px-3 py-1.5 rounded-xl border border-slate-700 transition font-medium"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5 text-indigo-400" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 text-xs bg-gradient-to-r from-indigo-600 to-indigo-500 hover:from-indigo-500 hover:to-indigo-400 text-white px-4 py-1.5 rounded-xl font-semibold transition shadow-md shadow-indigo-500/25"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download File</span>
            </button>
          </div>
        </div>

        {/* Content Preview */}
        <div className="p-5 overflow-y-auto flex-1 font-mono text-xs text-slate-200 bg-[#070d1a]">
          <pre className="whitespace-pre-wrap leading-relaxed">{content}</pre>
        </div>
      </div>
    </div>
  );
};
